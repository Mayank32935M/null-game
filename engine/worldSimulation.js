// Nonlethal Actions
// ---------------------------------------------------------------------------

/**
 * Processes a nonlethal player action that can affect crime and indicators.
 * Examples: leaking evidence, public statements, supporting investigations.
 *
 * @param {object} state
 * @param {string} actionType — e.g. 'leakEvidence', 'publicStatement', 'supportInvestigation'
 * @param {object} params — Action-specific parameters
 * @param {function} rng
 * @returns {object[]} Events generated
 */
export function processNonlethalAction(state, actionType, params, rng) {
  const events = [];

  switch (actionType) {
    case 'supportInvestigation': {
      // Player provides evidence to agencies (anonymously)
      state.crimeCategories.institutionalCapacity = Math.min(
        CRIME_CATEGORIES.institutionalCapacity.max,
        state.crimeCategories.institutionalCapacity + randomFloat(rng, 3, 8)
      );
      state.indicators.publicTrust += randomFloat(rng, 1, 3);
      state.indicators.playerExposure += randomFloat(rng, 2, 6); // Risk of discovery
      events.push(createEvent({
        type: EVENT_TYPES.PLAYER_ACTION,
        description: 'Anonymous evidence package delivered to investigators.',
        visibility: VISIBILITY.RESTRICTED,
        turn: state.turn,
        data: { actionType, deduplicationKey: `support_${state.turn}` },
      }));
      break;
    }
    case 'publicStatement': {
      // Player makes a public statement (risky)
      state.indicators.publicFear += randomFloat(rng, -5, 5);
      state.indicators.publicTrust += randomFloat(rng, -3, 3);
      state.indicators.playerExposure += randomFloat(rng, 5, 15);
      events.push(createEvent({
        type: EVENT_TYPES.PUBLIC_STATEMENT,
        description: params.content || 'A public statement was made.',
        visibility: VISIBILITY.PUBLIC,
        turn: state.turn,
        data: { actionType, content: params.content, deduplicationKey: `statement_${state.turn}` },
      }));
      break;
    }
    case 'wait': {
      // Player chooses to observe — no action, just advance time
      events.push(createEvent({
        type: EVENT_TYPES.PLAYER_ACTION,
        description: 'The bearer watches and waits.',
        visibility: VISIBILITY.PRIVATE,
        turn: state.turn,
        data: { actionType, deduplicationKey: `wait_${state.turn}` },
      }));
      break;
    }
    default:
      console.warn(`[WorldSimulation] Unknown nonlethal action type: ${actionType}`);
  }

  return events;
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function clamp(value, min, max) {
  return Math.max(min, Math.min(max, value));
}
