// ============================================================================
// NULL — World Simulation Engine
// Deterministic world advancement. This is the authoritative system for
// crime index, societal indicators, faction state, and world progression.
//
// CRIME INDEX FORMULA:
//   globalCrimeIndex = Σ(category.value * category.weight)
//   where institutionalCapacity is inverted (higher = lower crime)
//   Normalised to 0–200 range, then scaled to 0–100 for display.
//
// The AI NEVER touches this module. All state changes flow through here.
// ============================================================================

import { CRIME_CATEGORIES, SIM_PARAMS, FACTIONS, CHARACTERS, INDICATORS } from '../data/universe.js';
import { createEvent, EVENT_TYPES, VISIBILITY } from './eventEngine.js';
import { randomFloat, randomChance, randomInt } from './rng.js';

// ---------------------------------------------------------------------------
// Crime Index Calculation
// ---------------------------------------------------------------------------

/**
 * Computes the global crime index from individual crime categories.
 * Formula: weighted sum of category values, with institutional capacity inverted.
 *
 * Result is normalised to 0–100 scale where:
 *   100 = baseline crime level
 *   0   = no crime (theoretical minimum)
 *   25  = victory threshold
 *
 * @param {object} crimeCategories — { violent, organised, corruption, exploitation, institutionalCapacity }
 * @returns {number} The global crime index, clamped to [0, 100]
 */
export function computeCrimeIndex(crimeCategories) {
  let weightedSum = 0;

  for (const [key, config] of Object.entries(CRIME_CATEGORIES)) {
    const value = crimeCategories[key] ?? config.baseline;
    const clamped = Math.max(config.min, Math.min(config.max, value));

    if (config.inverted) {
      // Higher institutional capacity = LOWER crime contribution
      // Invert: a value of 200 contributes 0, a value of 0 contributes 200
      weightedSum += (config.max - clamped) * config.weight;
    } else {
      weightedSum += clamped * config.weight;
    }
  }

  // At baseline (all categories = 100), weightedSum = 100.
  // Clamped to [0, 100] for clean percentage scale.
  return Math.round(Math.max(0, Math.min(100, weightedSum)) * 10) / 10;
}

