/**
 * Processes the death of a character. Updates faction state, crime categories,
 * and produces consequential events (power vacuums, retaliation, etc).
 *
 * This is the ONLY function that should process character deaths.
 * The AI cannot bypass this.
 *
 * @param {object} state — The authoritative game state (mutated in-place)
 * @param {string} characterId — ID of the character who died
 * @param {string} cause — Cause of death key
 * @param {function} rng — Seeded RNG function
 * @returns {object[]} Array of events generated by this death
 */
export function processCharacterDeath(state, characterId, cause, rng) {
  const events = [];
  const character = state.characters[characterId];

  if (!character || !character.isAlive) {
    return events; // Already dead or doesn't exist
  }

  // Mark as dead
  character.isAlive = false;

  // Record the death event
  const deathEvent = createEvent({
    type: EVENT_TYPES.DEATH,
    description: `${character.name} (${character.role}) died of ${cause}.`,
    visibility: character.isPublicFigure ? VISIBILITY.PUBLIC : VISIBILITY.RESTRICTED,
    turn: state.turn,
    data: {
      characterId,
      cause,
      targetType: character.targetType,
      isPublicFigure: character.isPublicFigure,
      deduplicationKey: `death_${characterId}_${state.turn}`,
    },
    characterIds: [characterId],
    factionIds: character.factionId ? [character.factionId] : [],
  });
  events.push(deathEvent);

  // Apply crime impact — this is NOT automatic reduction!
  // Impact depends on the character's actual role and connections.
  if (character.crimeImpact) {
    for (const [category, delta] of Object.entries(character.crimeImpact)) {
      if (category in state.crimeCategories) {
        state.crimeCategories[category] = Math.max(
          CRIME_CATEGORIES[category].min,
          Math.min(
            CRIME_CATEGORIES[category].max,
            state.crimeCategories[category] + delta
          )
        );
      }
    }
  }

  // Process death consequences
  const consequences = character.deathConsequences || {};

  // Public fear
  if (consequences.publicFearDelta) {
    state.indicators.publicFear = clamp(
      state.indicators.publicFear + consequences.publicFearDelta,
      INDICATORS.publicFear.min,
      INDICATORS.publicFear.max
    );
  }

  // Public trust
  if (consequences.publicTrustDelta) {
    state.indicators.publicTrust = clamp(
      state.indicators.publicTrust + consequences.publicTrustDelta,
      INDICATORS.publicTrust.min,
      INDICATORS.publicTrust.max
    );
  }

  // Institutional stability
  if (consequences.institutionalStabilityDelta) {
    state.indicators.institutionalStability = clamp(
      state.indicators.institutionalStability + consequences.institutionalStabilityDelta,
      INDICATORS.institutionalStability.min,
      INDICATORS.institutionalStability.max
    );
  }

  // Power vacuum — when a faction leader dies
  if (consequences.powerVacuum && character.factionId) {
    const faction = state.factions[character.factionId];
    if (faction && faction.leaderId === characterId) {
      faction.stability -= consequences.factionStability || 30;
      faction.stability = Math.max(0, faction.stability);

      // Power vacuum causes INCREASE in crime (chaos)
      const vacuumSurge = SIM_PARAMS.powerVacuumCrimeSurge;
      for (const [cat, surge] of Object.entries(vacuumSurge)) {
        if (cat in state.crimeCategories) {
          // Scaled by the faction's original influence
          const scaledSurge = surge * (faction.influence / 100);
          state.crimeCategories[cat] = Math.min(
            CRIME_CATEGORIES[cat].max,
            state.crimeCategories[cat] + scaledSurge
          );
        }
      }

      // Record power vacuum event
      events.push(createEvent({
        type: EVENT_TYPES.POWER_VACUUM,
        description: `Power vacuum in ${faction.name} following the death of ${character.name}.`,
        visibility: VISIBILITY.RESTRICTED,
        turn: state.turn,
        data: {
          factionId: character.factionId,
          previousLeaderId: characterId,
          stabilityDrop: consequences.factionStability || 30,
          deduplicationKey: `vacuum_${character.factionId}_${state.turn}`,
        },
        factionIds: [character.factionId],
        characterIds: [characterId],
      }));

      // Track active power vacuums
      state.activePowerVacuums.push({
        factionId: character.factionId,
        startTurn: state.turn,
        duration: SIM_PARAMS.powerVacuumDuration,
      });
    }
  }

  // Retaliation check
  if (consequences.retaliationChance && randomChance(rng, consequences.retaliationChance)) {
    // Retaliation increases violent crime
    state.crimeCategories.violent = Math.min(
      CRIME_CATEGORIES.violent.max,
      state.crimeCategories.violent + randomInt(rng, 3, 8)
    );

    events.push(createEvent({
      type: EVENT_TYPES.FACTION_CHANGE,
      description: `Retaliation violence following the death of ${character.name}.`,
      visibility: VISIBILITY.PUBLIC,
      turn: state.turn,
      data: { type: 'retaliation', characterId, deduplicationKey: `retaliation_${characterId}_${state.turn}` },
      factionIds: character.factionId ? [character.factionId] : [],
    }));
  }

  return events;
}

// ---------------------------------------------------------------------------
// World Tick — advances the simulation by one turn
// ---------------------------------------------------------------------------

/**
 * Advances the world simulation by one turn. This is the core simulation loop.
 * Called after every player action or when the player chooses to wait.
 *
 * Processes:
 * 1. Natural crime drift (entropy — crime tends to rise without intervention)
 * 2. Power vacuum resolution
 * 3. Faction stability changes
 * 4. Indicator drift (fear decays, trust recovers)
 * 5. Institutional capacity effects
 * 6. Victory/defeat condition checks
 *
 * @param {object} state — The authoritative game state (mutated in-place)
 * @param {function} rng — Seeded RNG function
 * @returns {object} { events: Event[], crimeIndex: number, victoryCheck: object }
 */
export function advanceWorld(state, rng) {
  const events = [];
  state.turn += 1;

  // 1. Natural crime drift — crime doesn't just go away on its own
  for (const [key, config] of Object.entries(CRIME_CATEGORIES)) {
    if (!config.inverted) {
      state.crimeCategories[key] = Math.min(
        config.max,
        state.crimeCategories[key] + SIM_PARAMS.naturalCrimeDrift * randomFloat(rng, 0.5, 1.5)
      );
    }
  }

  // 2. Process active power vacuums
  state.activePowerVacuums = state.activePowerVacuums.filter(vacuum => {
    const turnsElapsed = state.turn - vacuum.startTurn;
    if (turnsElapsed >= vacuum.duration) {
      // Vacuum resolved — crime surge stabilises
      // But doesn't automatically go back down
      events.push(createEvent({
        type: EVENT_TYPES.FACTION_CHANGE,
        description: `Power struggle in ${state.factions[vacuum.factionId]?.name || 'unknown faction'} has stabilised.`,
        visibility: VISIBILITY.PUBLIC,
        turn: state.turn,
        data: { type: 'vacuum_resolved', factionId: vacuum.factionId },
      }));
      return false; // Remove from active list
    }
    return true; // Keep active
  });

  // 3. Faction stability recovery
  for (const faction of Object.values(state.factions)) {
    if (faction.stability < 100) {
      faction.stability = Math.min(100, faction.stability + randomFloat(rng, 0.5, 2));
    }
  }

  // 4. Indicator drift
  // Fear decays naturally
  state.indicators.publicFear = clamp(
    state.indicators.publicFear + SIM_PARAMS.naturalFearDecay,
    INDICATORS.publicFear.min,
    INDICATORS.publicFear.max
  );

  // Trust recovers slowly
  state.indicators.publicTrust = clamp(
    state.indicators.publicTrust + SIM_PARAMS.naturalTrustRecovery * randomFloat(rng, 0.5, 1.5),
    INDICATORS.publicTrust.min,
    INDICATORS.publicTrust.max
  );

  // 5. Institutional capacity responds to stability
  const stabilityFactor = state.indicators.institutionalStability / 100;
  state.crimeCategories.institutionalCapacity = clamp(
    state.crimeCategories.institutionalCapacity + (stabilityFactor - 0.5) * 2,
    CRIME_CATEGORIES.institutionalCapacity.min,
    CRIME_CATEGORIES.institutionalCapacity.max
  );

  // 6. Compute the crime index
  const crimeIndex = computeCrimeIndex(state.crimeCategories);
  state.crimeIndex = crimeIndex;

  // Track crime index history for stability check
  state.crimeIndexHistory.push(crimeIndex);
  if (state.crimeIndexHistory.length > 20) {
    state.crimeIndexHistory.shift();
  }

  // 7. Victory check
  const victoryCheck = checkVictoryCondition(state);

  // 8. Record world tick event
  events.push(createEvent({
    type: EVENT_TYPES.WORLD_TICK,
    description: `World advanced to turn ${state.turn}. Crime index: ${crimeIndex}.`,
    visibility: VISIBILITY.PRIVATE,
    turn: state.turn,
    data: { crimeIndex, turn: state.turn },
  }));

  return { events, crimeIndex, victoryCheck };
}

// ---------------------------------------------------------------------------
// Victory Condition
// ---------------------------------------------------------------------------

/**
 * Checks whether the victory condition is met.
 * Crime index must be below 25 for SIM_PARAMS.victoryStabilityTurns consecutive turns.
 *
 * @param {object} state — The authoritative game state
 * @returns {object} { met: boolean, turnsBelow: number, required: number }
 */
export function checkVictoryCondition(state) {
  const threshold = SIM_PARAMS.crimeIndexVictoryThreshold;
  const required = SIM_PARAMS.victoryStabilityTurns;
  const history = state.crimeIndexHistory;

  // Count consecutive turns below threshold from the end
  let turnsBelow = 0;
  for (let i = history.length - 1; i >= 0; i--) {
    if (history[i] < threshold) {
      turnsBelow++;
    } else {
      break;
    }
  }

  return {
    met: turnsBelow >= required,
    turnsBelow,
    required,
    currentIndex: state.crimeIndex,
    threshold,
  };
}

// ---------------------------------------------------------------------------
// Defeat Conditions
// ---------------------------------------------------------------------------

/**
 * Checks all defeat conditions.
 * @param {object} state
 * @returns {object|null} Defeat descriptor or null if no defeat
 */
export function checkDefeatConditions(state) {
  // Lifespan zero
  if (state.lifespanDays <= 0) {
    return { type: 'consumed', reason: 'Bearer lifespan reached zero.' };
  }

  // Exposure maxed
  if (state.indicators.playerExposure >= 95) {
    return { type: 'exposed', reason: 'The agencies have identified the bearer.' };
  }

  return null;
}

// ---------------------------------------------------------------------------
// Ending Determination
// ---------------------------------------------------------------------------

/**
 * Determines which ending the player receives based on current state.
 * Called when victory is achieved or the game ends.
 *
 * @param {object} state
 * @returns {object} The ending descriptor
 */
export function determineEnding(state) {
  if (state.lifespanDays <= 0) {
    return { id: 'consumed', name: 'Consumed', description: 'The Ledger claims its final price.' };
  }

  if (state.indicators.playerExposure >= 95) {
    return { id: 'exposed', name: 'Exposed', description: 'The agencies identified the bearer.' };
  }

  if (state.crimeIndex < SIM_PARAMS.crimeIndexVictoryThreshold) {
    // Victory — but what kind?
    if (state.indicators.publicFear > 60) {
      return { id: 'fearfulOrder', name: 'Fearful Order', description: 'Order through fear, not trust.' };
    }
    if (state.indicators.institutionalStability < 30) {
      return { id: 'unstableVictory', name: 'Unstable Victory', description: 'The peace is fragile.' };
    }
    if (state.indicators.publicFear < 30 && state.indicators.publicTrust > 50 && state.indicators.playerExposure < 40) {
      return { id: 'quietReformer', name: 'The Quiet Reformer', description: 'The bearer chose restraint.' };
    }
    return { id: 'victory', name: 'A Changed World', description: 'Crime fell below 25. The world is different now.' };
  }

  return { id: 'stalemate', name: 'Stalemate', description: 'Crime never fell below 25.' };
}

